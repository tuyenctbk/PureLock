def escape_for_android_xml(text):
    if text is None:
        return ""
    text = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    text = text.replace(r"\'", "'").replace(r'\"', '"')
    
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", r"\'")
    text = text.replace('"', r'\"')
    return text

def parse_base_strings(base_path):
    with open(base_path, "r", encoding="utf-8") as f:
        content = f.read()
    
    pattern = re.compile(r'<string\s+name="([^"]+)">([\s\S]*?)</string>')
    items = []
    for m in pattern.finditer(content):
        name = m.group(1)
        raw_val = m.group(2)
        items.append((name, raw_val))
    return items

def parse_existing_strings(file_path):
    if not os.path.exists(file_path):
        return {}
    with open(file_path, "r", encoding="utf-8") as f:
        content = f.read()
    pattern = re.compile(r'<string\s+name="([^"]+)">([\s\S]*?)</string>')
    result = {}
    for m in pattern.finditer(content):
        name = m.group(1)
        raw_val = m.group(2)
        result[name] = raw_val
    return result

