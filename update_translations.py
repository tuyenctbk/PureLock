def update_all_locales():
    base_file = "app/src/main/res/values/strings.xml"
    base_items = parse_base_strings(base_file)
    print(f"Loaded {len(base_items)} base strings.")

    res_dir = "app/src/main/res"
    val_dirs = sorted([d for d in os.listdir(res_dir) if d.startswith("values-") and os.path.isfile(os.path.join(res_dir, d, "strings.xml"))])

    for d in val_dirs:
        lang_code = d.replace("values-", "")
        file_path = os.path.join(res_dir, d, "strings.xml")
        existing = parse_existing_strings(file_path)

        out_lines = ['<?xml version="1.0" encoding="utf-8"?>\n<resources>\n']
        
        for name, base_val in base_items:
            val = None
            if lang_code == "vi" and name in VI_MAP:
                val = VI_MAP[name]
            elif (lang_code == "es" or lang_code.startswith("es")) and name in ES_MAP:
                val = ES_MAP[name]
            elif lang_code in COMMON_TRANSLATIONS and name in COMMON_TRANSLATIONS[lang_code]:
                val = COMMON_TRANSLATIONS[lang_code][name]
            elif name in existing:
                val = existing[name]
            elif lang_code == "vi" and name in VI_MAP:
                val = VI_MAP[name]
            elif lang_code == "es" and name in ES_MAP:
                val = ES_MAP[name]
            else:
                val = existing.get(name, base_val)

            escaped = escape_for_android_xml(val)
            out_lines.append(f'    <string name="{name}">{escaped}</string>\n')

        out_lines.append('</resources>\n')

        with open(file_path, "w", encoding="utf-8") as f:
            f.writelines(out_lines)

        print(f"Updated {file_path} with {len(base_items)} keys.")

if __name__ == "__main__":
    update_all_locales()
